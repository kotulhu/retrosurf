    /// Личная страничка пользователя каталога. Номер /p/N.html (1-based)
    /// соответствует записи в `catalogUsers`; контент берётся из
    /// `personalPages`. Для неизвестного номера/владельца — заглушка.
    static func personalPage(path: String) -> String {
        let raw = path
            .replacingOccurrences(of: "/p/", with: "")
            .replacingOccurrences(of: ".html", with: "")
            .trimmingCharacters(in: .whitespacesAndNewlines)
        guard let index = Int(raw),
              index >= 1,
              index <= catalogUsers.count else {
            return personalPageShell(name: nil, body: placeholderBody)
        }
        let name = catalogUsers[index - 1]
        let body = personalPages[name] ?? placeholderBody
        return personalPageShell(name: name, body: body)
    }

    private static var placeholderBody: String {
        "<p>Здесь скоро появится настоящее содержимое сайта.</p>"
    }

    private static func personalPageShell(name: String?, body: String) -> String {
        let heading = name.map { "Личная страничка · \(escapeHTML($0))" } ?? "Личная страничка"
        return """
        <html><head><meta charset="utf-8"><title>\(heading)</title>
