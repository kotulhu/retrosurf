        h1{font-size:22px}p{font-size:14px;line-height:1.5}a{color:#0000aa}</style>
        </head><body>
        <h1>\(heading)</h1>
        \(body)
        <p><a href="/">← На главную</a></p>
        </body></html>
        """
    }

